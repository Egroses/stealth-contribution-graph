def glyph(ch):
    body = GLYPHS.get(ch.upper(), GLYPHS["?"])
    width = len(body[0])
    return ["." * width] + body + ["." * width]


def text_width(text, px, spacing=1):
    total = 0
    for i, ch in enumerate(text):
        total += len(glyph(ch)[0]) * px
        if i < len(text) - 1:
            total += spacing * px
    return total


def pixel_path(text, x, y, px, spacing=1):
    parts = []
    cursor = x
    for ch in text:
        rows = glyph(ch)
        width = len(rows[0])
        for r, row in enumerate(rows):
            c = 0
            while c < width:
                if row[c] == "#":
                    start = c
                    while c < width and row[c] == "#":
                        c += 1
                    run = c - start
                    gx = cursor + start * px
                    gy = y + (r - 1) * px
                    parts.append(f"M{gx:g} {gy:g}h{run * px:g}v{px:g}h{-run * px:g}z")
                else:
                    c += 1
        cursor += (width + spacing) * px
    return "".join(parts)


def pixel_text(text, x, y, px, fill, anchor="start", spacing=1):
    w = text_width(text, px, spacing)
    if anchor == "middle":
        x = x - w / 2
    elif anchor == "end":
        x = x - w
    return f'<path d="{pixel_path(text, x, y, px, spacing)}" fill="{fill}" shape-rendering="crispEdges"/>'


def svg(width, height, body, defs="", label=""):
    head = f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img"'
    head += f' aria-label="{label}">' if label else ">"
    out = [head]
    if label:
        out.append(f"<title>{label}</title>")
    if defs:
        out.append(f"<defs>{defs}</defs>")
    out.append(body)
    out.append("</svg>")
    return "\n".join(out)


def write(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return path
